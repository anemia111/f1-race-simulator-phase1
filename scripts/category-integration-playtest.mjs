import { preview } from 'vite'
import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const out=resolve(process.env.CATEGORY_QA_DIR ?? '../../outputs/category-integration-qa');await mkdir(out,{recursive:true})
const server=await preview({logLevel:'error',preview:{host:'127.0.0.1',port:0}})
const browser=await chromium.launch({headless:true})
const results=[],errors=[]
try{
 const page=await browser.newPage({viewport:{width:1920,height:1080}})
 page.on('pageerror',error=>errors.push(error.message))
 await page.route('https://api.openf1.org/**',route=>route.abort())
 await page.goto(process.env.APP_URL ?? `http://127.0.0.1:${server.httpServer.address().port}/`)
 await page.waitForSelector('.leaderboard-rows li')
 await page.getByRole('button',{name:'Skip formation lap',exact:true}).click()
 await page.getByRole('button',{name:'Telemetry',exact:true}).click()
 await page.getByLabel('Telemetry comparison car').waitFor()
 await page.waitForFunction(()=>Number(document.querySelector('.telemetry-legends')?.textContent?.match(/A ·.*?· ([0-9]+)点/)?.[1]??0)>=20,{}, {timeout:45000})
 const f1Points=await page.locator('.telemetry-legends').innerText()
 const groups=['ドライビング','グリップ・車体','タイヤ・ブレーキ','燃料・エネルギー']
 for(const name of groups)await page.getByRole('button',{name,exact:true}).click()
 await page.getByLabel('Telemetry lap A').selectOption('current')
 await page.getByLabel('Telemetry lap B').selectOption('current')
 const csv=page.waitForEvent('download');await page.getByRole('button',{name:'CSVを書き出す',exact:true}).click();await(await csv).saveAs(resolve(out,'f1-telemetry.csv'))
 await page.screenshot({path:resolve(out,'f1-telemetry.png')})
 results.push({category:'f1-custom',telemetry:f1Points,groups:4,csvExport:true})
 for(const id of ['wec','super-gt','kyojo','indycar']){
  await page.getByLabel('Racing series',{exact:true}).selectOption(`motorsport:${id}`)
  await page.waitForFunction(id=>document.querySelector('[aria-label="Racing series"]')?.value===`motorsport:${id}`,id)
  await page.getByRole('button',{name:'Resume simulation',exact:true}).waitFor()
  const count=await page.locator('.leaderboard-rows li').count()
  const before=await page.locator('.broadcast-session-core time').innerText()
  const skip=page.getByRole('button',{name:'Skip formation lap',exact:true});if(await skip.count())await skip.click()
  await page.getByRole('button',{name:'20x',exact:true}).click()
  await page.getByRole('button',{name:'Resume simulation',exact:true}).click()
  await page.waitForFunction(before=>document.querySelector('.broadcast-session-core time')?.textContent!==before,before)
  if(!await page.getByLabel('Telemetry comparison car').count()) await page.getByRole('button',{name:'Telemetry',exact:true}).click()
  await page.getByLabel('Telemetry comparison car').waitFor()
  await page.waitForFunction(()=>/A ·[^\n]+· [1-9][0-9]*点/.test(document.querySelector('.telemetry-legends')?.textContent??''),{}, {timeout:45000})
  await page.getByRole('button',{name:'Pause simulation',exact:true}).click()
  const traces=await page.locator('.telemetry-legends').innerText()
  await page.getByLabel('Telemetry lap A').selectOption('current')
  await page.getByRole('button',{name:'燃料・エネルギー',exact:true}).click()
  await page.screenshot({path:resolve(out,`${id}-telemetry.png`)})
  results.push({category:id,cars:count,clockAdvanced:true,telemetry:traces})
 }
 await page.getByLabel('Racing series',{exact:true}).selectOption('f1-custom')
 await page.getByRole('button',{name:'Map',exact:true}).waitFor()
 await page.locator('.sidebar-settings').click()
 const rounds=page.getByLabel('Championship round')
 const suzuka=await rounds.locator('option').evaluateAll(options=>options.find(option=>/suzuka/i.test(option.textContent))?.value)
 await rounds.selectOption(suzuka)
 await page.getByLabel('close setup').click()
 await page.getByRole('button',{name:'Cinematic',exact:true}).click()
 await page.waitForSelector('.cinematic-view')
 await page.getByLabel('Cinematic camera').selectOption('onboard')
 await page.screenshot({path:resolve(out,'integrated-f1-cinematic.png')})
 results.push({returnToF1:true,suzukaCinematic:true,onboard:true})
 if(errors.length)throw new Error(errors.join('\n'))
 await writeFile(resolve(out,'results.json'),JSON.stringify({results,errors},null,2))
 console.log(JSON.stringify({results,errors},null,2))
}finally{await browser.close();await new Promise(resolve=>server.httpServer.close(resolve))}
