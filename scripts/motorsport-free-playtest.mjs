import { chromium } from 'playwright'
import { preview } from 'vite'
import { mkdir } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { tmpdir } from 'node:os'
import assert from 'node:assert/strict'

const root = resolve(import.meta.dirname,'..')
const artifacts = resolve(process.env.QA_ARTIFACT_DIR || join(tmpdir(),'f1-simulator-qa'))
await mkdir(artifacts,{recursive:true})
const server = await preview({root,logLevel:'error',preview:{host:'127.0.0.1',port:0}})
const browser = await chromium.launch({headless:true}), errors=[], reports=[]
try {
  for (const viewport of [{width:1440,height:900},{width:1280,height:720}]) {
    const page=await browser.newPage({viewport,acceptDownloads:true})
    page.on('pageerror',error=>errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
    await page.getByRole('button',{name:'FREE',exact:true}).click()
    const builder=page.getByRole('dialog',{name:'Free Mode session builder',exact:true})
    await builder.getByLabel('Free Mode category',{exact:true}).selectOption('motorsport:wec')
    await page.getByTestId('motorsport-app').waitFor()
    await page.getByLabel('Free Mode category',{exact:true}).selectOption('super-gt')
    await page.getByLabel('Free Mode category',{exact:true}).selectOption('wec')
    await page.getByLabel('Free Mode track',{exact:true}).selectOption('monaco-approx')
    await page.getByLabel('Free Mode cars',{exact:true}).fill('3')
    await builder.getByRole('button',{name:'Apply',exact:true}).click()
    const rows=builder.locator('.free-mode-entry-row')
    assert.equal(await rows.count(),3)
    await page.getByLabel('Vehicle for grid 2',{exact:true}).waitFor()
    const vehicleOptions=await page.getByLabel('Vehicle for grid 2',{exact:true}).locator('option').evaluateAll(options=>options.map(option=>({value:option.value,text:option.textContent})))
    await page.getByLabel('Vehicle for grid 2',{exact:true}).selectOption(vehicleOptions.find(option=>option.text.startsWith('LMP2'))?.value)
    await page.getByLabel('Vehicle for grid 3',{exact:true}).selectOption(vehicleOptions.find(option=>option.text.startsWith('LMGT3'))?.value)
    await page.getByRole('button',{name:'Move grid 2 up',exact:true}).click()
    await page.getByRole('button',{name:'Duplicate vehicle at grid 1',exact:true}).click()
    assert.equal(await rows.count(),4)
    await page.getByRole('button',{name:'Delete grid 4',exact:true}).click()
    await page.getByLabel('Search Free Mode drivers',{exact:true}).fill('Verstappen')
    const driverOptions=await page.getByLabel('Driver for grid 1 crew 1',{exact:true}).locator('option').evaluateAll(options=>options.map(option=>({value:option.value,text:option.textContent})))
    await page.getByLabel('Driver for grid 1 crew 1',{exact:true}).selectOption(driverOptions.find(option=>option.text.includes('Max Verstappen'))?.value)
    await page.getByLabel('Search Free Mode drivers',{exact:true}).fill('')
    await page.getByLabel('Free Mode session',{exact:true}).selectOption('qualifying')
    await page.getByLabel('Free Mode distance',{exact:true}).fill('6')
    await page.getByLabel('Free Mode preset name',{exact:true}).fill('Mixed class QA')
    await page.getByRole('button',{name:'Save preset',exact:true}).click()
    const download=page.waitForEvent('download')
    await page.getByRole('button',{name:'Export JSON',exact:true}).click()
    const savePath=join(artifacts,`free-mode-${viewport.width}.json`)
    await (await download).saveAs(savePath)
    await page.getByLabel('Import Free Mode configuration',{exact:true}).setInputFiles(savePath)
    await page.screenshot({path:join(artifacts,`motorsport-free-builder-${viewport.width}.png`),fullPage:true})
    const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,footer:document.querySelector('.free-mode-footer').getBoundingClientRect().bottom}))
    assert.ok(layout.scroll<=layout.width+1)
    assert.ok(layout.footer<=viewport.height)
    await page.getByRole('button',{name:'Start session',exact:true}).click()
    assert.equal(await page.getByRole('button',{name:'FREE',exact:true}).getAttribute('aria-pressed'),'true')
    assert.equal(await page.locator('.leaderboard-rows > li').count(),3)
    assert.equal(await page.getByLabel('Weekend session',{exact:true}).inputValue(),'qualifying')
    await page.getByRole('button',{name:'Pause simulation',exact:true}).click()
    await page.getByRole('button',{name:'PIT WALL',exact:true}).click()
    for (const tab of ['OVERVIEW','LAP LOG','STRATEGY','CAR SYSTEMS','WEATHER & TRACK','RACE CONTROL']) await page.getByRole('tab',{name:tab,exact:true}).click()
    await page.getByRole('button',{name:'SAVE',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('[aria-label="Driver pace instruction"] button[aria-pressed="true"]')?.textContent==='SAVE')
    await page.getByRole('tab',{name:'STRATEGY',exact:true}).click()
    await page.screenshot({path:join(artifacts,`motorsport-pit-wall-${viewport.width}.png`),fullPage:true})
    await page.getByRole('button',{name:'Close pit wall',exact:true}).click()
    await page.getByRole('button',{name:'600x',exact:true}).click()
    await page.getByRole('button',{name:'Resume simulation',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.broadcast-phase-label')?.textContent==='FINISHED',null,{timeout:60000})
    await page.getByTitle('Selected driver analysis',{exact:true}).click()
    assert.ok(await page.getByRole('dialog',{name:'driver analysis',exact:true}).locator('tbody tr').count()>0)
    assert.equal(await page.getByLabel('Telemetry comparison').getByRole('img').count(),4)
    assert.equal(await page.getByLabel('Telemetry comparison car').locator('option').count(),2)
    assert.ok(await page.getByLabel('Telemetry comparison').locator('svg path[d]').count()>0)
    await page.screenshot({path:join(artifacts,`telemetry-comparison-${viewport.width}.png`),fullPage:true})
    await page.getByRole('button',{name:'Close panel',exact:true}).click()
      await page.getByTitle('Telemetry',{exact:true}).click()
      const telemetryWorkspace=page.getByLabel('Telemetry workspace',{exact:true})
      assert.equal(await telemetryWorkspace.getByRole('img').count(),4)
      assert.equal(await page.getByLabel('Telemetry primary car',{exact:true}).locator('option').count(),3)
      assert.ok(await telemetryWorkspace.locator('svg path').evaluateAll(paths=>paths.some(path=>(path.getAttribute('d')??'').length>100)))
      await page.screenshot({path:join(artifacts,`telemetry-workspace-${viewport.width}.png`),fullPage:true})
      await page.getByRole('button',{name:'Close telemetry comparison',exact:true}).click()
    await page.getByRole('button',{name:'FREE',exact:true}).click()
    await page.getByLabel('Free Mode session',{exact:true}).selectOption('race')
    await page.getByLabel('Free Mode distance',{exact:true}).fill('1')
    await page.getByLabel('Free Mode grid',{exact:true}).selectOption('qualifying-result')
    await page.getByRole('button',{name:'Start session',exact:true}).click()
    await page.getByRole('button',{name:'Skip formation lap',exact:true}).click()
    await page.getByRole('button',{name:'600x',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.broadcast-phase-label')?.textContent==='FINISHED',null,{timeout:60000})
    await page.getByRole('button',{name:'CHAMP',exact:true}).click()
    assert.equal(await page.locator('.leaderboard-rows > li').count(),35)
    assert.equal(await page.getByRole('button',{name:'CHAMP',exact:true}).getAttribute('aria-pressed'),'true')
    const stores=await page.evaluate(()=>[localStorage.getItem('race-sim-motorsport-2026-v1'),localStorage.getItem('race-sim-motorsport-free-v1')].map(raw=>JSON.parse(JSON.parse(raw).payload)))
    assert.equal(stores[0].config.entries.length,35)
    assert.equal(stores[1].config.entries.length,3)
    for (const category of ['kyojo','super-gt','indycar']) {
      await page.getByRole('button',{name:'FREE',exact:true}).click()
      await page.getByLabel('Free Mode category',{exact:true}).selectOption(category)
      await page.getByLabel('Free Mode cars',{exact:true}).fill('3')
      await builder.getByRole('button',{name:'Apply',exact:true}).click()
      await page.getByLabel('Free Mode distance',{exact:true}).fill('1')
      await page.getByLabel('Free Mode grid',{exact:true}).selectOption('random')
      if(category==='indycar') await page.getByLabel('Free Mode track',{exact:true}).selectOption('indianapolis-500')
      await page.getByRole('button',{name:'Start session',exact:true}).click()
      assert.equal(await page.locator('.leaderboard-rows > li').count(),3)
      await page.getByRole('button',{name:'600x',exact:true}).click()
      await page.waitForFunction(()=>document.querySelector('.broadcast-phase-label')?.textContent==='FINISHED',null,{timeout:60000})
      await page.getByRole('button',{name:'CHAMP',exact:true}).click()
      assert.equal(await page.locator('.leaderboard-rows > li').count(),35)
    }
    await page.getByRole('button',{name:'FREE',exact:true}).click()
    await page.getByLabel('Free Mode category',{exact:true}).selectOption('super-formula')
    await page.waitForFunction(()=>document.querySelector('.free-mode-settings select')?.value==='super-formula'||[...document.querySelectorAll('.free-mode-settings select')].some(select=>select.value==='super-formula'))
    assert.equal(await page.getByRole('dialog',{name:'Free Mode session builder',exact:true}).count(),1)
    await page.getByRole('button',{name:'Close Free Mode Builder',exact:true}).click()
    reports.push({viewport,qualifying:true,mixedClasses:3,freeCategories:['wec','kyojo','super-gt','indycar'],freeChampIsolation:true,pitTabs:6,layout})
    await page.close()
    console.log(`[motorsport-free-playtest] ${viewport.width}: passed`)
  }
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({ok:true,reports,errors},null,2))
} finally {await browser.close();await new Promise(resolveClose=>server.httpServer.close(resolveClose))}
